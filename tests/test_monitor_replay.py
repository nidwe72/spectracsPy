def test_the_fixture_covers_every_monitored_run_the_archive_holds():
    runs = loadRuns()
    assert len(runs) == 16, "the archive holds sixteen monitored runs; the fixture has %d" % len(runs)
    assert sum(len(run["rows"]) for run in runs) == 379


@pytest.mark.parametrize("run", loadRuns(), ids=lambda run: run["id"])
def test_the_real_evaluator_reproduces_the_pinned_answer(run):
    """⭐ THE point of the harness. A change to any read rule shows up here, run by run, as a diff."""
    answer = replay(run)
    expected = run["expected"]
    if expected["value"] is None:
        assert answer is None or answer["value"] is None, \
            "%s: expected NO answer, got %r" % (run["id"], answer and answer["value"])
        return
    assert answer is not None, "%s: expected %.4f, got no answer at all" % (run["id"], expected["value"])
    assert answer["value"] == pytest.approx(expected["value"], abs=1e-6), \
        "%s: %.4f -> %.4f" % (run["id"], expected["value"], answer["value"])
    assert answer["readAs"] == expected["readAs"]
    assert answer["branch"] == expected["branch"]


@pytest.mark.parametrize("run", loadRuns(), ids=lambda run: run["id"])
def test_every_answer_comes_from_the_END_OF_RUN_read(run):
    """§45/M2 — a core/plugin repo skew fails SILENTLY: the probe finds no `finalize`, the run reverts to
    the gate-time answer, and nothing says so. `readPhase` is the detector, so the harness asserts it."""
    answer = replay(run)
    if answer is None:
        return
    assert answer["readPhase"] == "final", \
        "%s read at the GATE — either finalize is missing (a repo skew) or it declined" % run["id"]


